CREATE OR REPLACE TRIGGER generate_account_id_trigger
BEFORE INSERT ON Account
FOR EACH ROW
BEGIN
    :NEW.Account_id := generate_account_id(:NEW.AccName, :NEW.AccCode, :NEW.OpenningDate);
END;
/


