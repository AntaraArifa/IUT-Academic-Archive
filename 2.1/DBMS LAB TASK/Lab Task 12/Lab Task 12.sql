-- Drop the foreign key constraint in the AccountProperty table
ALTER TABLE AccountProperty DROP CONSTRAINT ACCOUNTPROPERTY_FK;

-- Drop the ID column in the Account table
ALTER TABLE Account DROP COLUMN ID;

-- Add the Account_id column to the Account table
ALTER TABLE Account ADD (Account_id VARCHAR2(50));

-- Update the Account_id column with the values generated by the generate_account_id function
UPDATE Account SET Account_id = generate_account_id(AccName, AccCode, OpenningDate);

-- Add a primary key constraint to the Account_id column in the Account table
ALTER TABLE Account ADD CONSTRAINT ACCOUNT_PK PRIMARY KEY (Account_id);

-- Update the foreign key constraint in the AccountProperty table to reference the Account_id column
ALTER TABLE AccountProperty ADD CONSTRAINT ACCOUNTPROPERTY_FK FOREIGN KEY (AP_ID) REFERENCES Account(Account_id);


