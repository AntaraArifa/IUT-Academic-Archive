
CREATE TABLE TRANSACTION(
    TID INT NOT NULL,
    AccNo INT NOT NULL,
    Amount Numeric(10,2) NOT NULL,
    TransactionDate TIMESTAMP NOT NULL,
    CONSTRAINT TRANSACTION_PK PRIMARY KEY(TID)
);

CREATE TABLE Balance(
    AccNo INT NOT NULL,
    PrincipalAmount Numeric(10,2) NOT NULL,
    ProfitAmount Numeric(10,2) NOT NULL,
    CONSTRAINT BALANCE_PK PRIMARY KEY(AccNo)
);

CREATE TABLE Account(
    ID INT NOT NULL,
    AccName VARCHAR(50) NOT NULL,
    AccCode int NOT NULL,
    AccNo INT NOT NULL,
    OpenningDate TIMESTAMP NOT NULL,
    LastDateInterest TIMESTAMP NOT NULL,
    CONSTRAINT ACCOUNT_PK PRIMARY KEY(ID),
    CONSTRAINT ACCOUNT_FK FOREIGN KEY(AccNo) REFERENCES Balance(AccNo),
    CONSTRAINT ACCOUNT_FK1 FOREIGN KEY(AccNo) REFERENCES TRANSACTION(AccNo)
);

CREATE TABLE AccountProperty(
    AP_ID INT NOT NULL,
    AP_Name VARCHAR(50) NOT NULL,
    ProfileRate Numeric(10,2) NOT NULL,
    GracePeriod INT NOT NULL,
    CONSTRAINT ACCOUNTPROPERTY_PK PRIMARY KEY(AP_ID),
    CONSTRAINT ACCOUNTPROPERTY_FK FOREIGN KEY(AP_ID) REFERENCES Account(ID)
);


