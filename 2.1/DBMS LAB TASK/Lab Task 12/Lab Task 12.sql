CREATE OR REPLACE TRIGGER update_balance_after_transaction
AFTER INSERT ON TRANSACTION
FOR EACH ROW
BEGIN
    UPDATE Balance
    SET PrincipalAmount = PrincipalAmount + :NEW.Amount
    WHERE AccNo = :NEW.AccNo;
END;
