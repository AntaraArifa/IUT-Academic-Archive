CREATE OR REPLACE TRIGGER insert_balance_after_account
AFTER INSERT ON Account
FOR EACH ROW
BEGIN
    INSERT INTO Balance (AccNo, PrincipalAmount, ProfitAmount)
    VALUES (:NEW.Account_id, 5000, 0);
END;
/


