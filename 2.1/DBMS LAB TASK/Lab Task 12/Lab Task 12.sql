CREATE SEQUENCE serial_seq START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE FUNCTION generate_account_id(
    p_name IN VARCHAR2,
    p_acc_code IN NUMBER,
    p_open_date IN DATE
) RETURN VARCHAR2 IS
    v_account_id VARCHAR2(50);
    v_serial_no NUMBER;
BEGIN
    SELECT serial_seq.NEXTVAL INTO v_serial_no FROM dual;
    
    v_account_id := TO_CHAR(p_acc_code, 'FM0000') || 
                    TO_CHAR(p_open_date, 'YYYYMMDD') || '.' ||
                    SUBSTR(p_name, 1, 3) || '.' ||
                    TO_CHAR(v_serial_no, 'FM000000');
                    
    RETURN v_account_id;
END generate_account_id;
/

