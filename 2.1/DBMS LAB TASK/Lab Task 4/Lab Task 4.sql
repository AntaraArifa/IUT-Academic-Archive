SELECT ACT_FIRSTNAME || ' '|| ACT_LASTNAME AS ACT_NAME
FROM ACTOR
WHERE ACT_GENDER = 'F'
AND ACT_FIRSTNAME IN (
    SELECT ACT_FIRSTNAME
    FROM ACTOR
    WHERE ACT_GENDER = 'F'
    GROUP BY ACT_FIRSTNAME
    HAVING COUNT(*) > 1
);


