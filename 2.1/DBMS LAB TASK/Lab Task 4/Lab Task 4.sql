SELECT DISTINCT A.ACT_FIRSTNAME, A.ACT_LASTNAME 
FROM 
( SELECT ACT_FIRSTNAME ,ACT_LASTNAME
  FROM ACTOR
  UNION
  SELECT DIR_FIRSTNAME,DIR_LASTNAME
  FROM DIRECTOR
)a
JOIN
(
  SELECT ACT_FIRSTNAME ,ACT_LASTNAME
  FROM ACTOR
  INTRSECT
  SELECT DIR_FIRSTNAME,DIR_LASTNAME
  FROM DIRECTOR
)b
SELECT a.ACT-FIRSTNAME=b.ACT_FIRSTNAME AND a.ACT-LASTNAME=b.ACT_LASTNAME;


