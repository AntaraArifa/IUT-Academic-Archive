FROM ACTOR
UNION
SELECT DIR_FIRSTNAME || ' ' || DIR_LASTNAME AS FULL_NAME
FROM DIRECTOR
UNION
SELECT REV_NAME AS FULL_NAME
FROM REVIEWER;

4--
SELECT MOV_TITLE
FROM MOVIE
WHERE MOV_ID NOT IN (SELECT MOV_ID FROM RATING);

5--
SELECT AVG(REV_STARS) AS AVERAGE_RATING
FROM RATING;

6--
SELECT MOV_TITLE, MIN(REV_STARS) AS MIN_RATING
FROM MOVIE
JOIN RATING ON MOVIE.MOV_ID = RATING.MOV_ID
GROUP BY MOV_TITLE
ORDER BY MIN_RATING DESC;


7--
SELECT MOV_TITLE
FROM MOVIE
GROUP BY MOV_TITLE
HAVING AVG(REV_STARS) > (SELECT AVG(REV_STARS) FROM RATING);

8--
SELECT A.ACT_FIRSTNAME, A.ACT_LASTNAME, COUNT(R.REV_ID) AS NUM_RATINGS
FROM ACTOR A
JOIN CASTS C ON A.ACT_ID = C.ACT_ID
JOIN RATING R ON C.MOV_ID = R.MOV_ID
GROUP BY A.ACT_FIRSTNAME, A.ACT_LASTNAME;

9--
SELECT D.DIR_FIRSTNAME, D.DIR_LASTNAME
FROM DIRECTOR D
JOIN MOVIE M ON D.DIR_ID = M.DIR_ID
GROUP BY D.DIR_FIRSTNAME, D.DIR_LASTNAME
HAVING AVG(M.REV_STARS) = (SELECT MAX(AVG_REV_STARS) FROM (
    SELECT M.DIR_ID, AVG(M.REV_STARS) AS AVG_REV_STARS
    FROM MOVIE M
    GROUP BY M.DIR_ID
));

